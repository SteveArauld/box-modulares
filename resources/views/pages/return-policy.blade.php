										<h2>1. Objeto</h2>
										<p>La presente Política de Devoluciones y Reembolsos regula las condiciones
											aplicables a las devoluciones, cambios y reembolsos de los productos
											adquiridos a través del sitio web <strong><a
													href="../">https://domaine.it</a></strong>, de
											conformidad con la normativa española y europea en materia de protección de
											los consumidores.</p>
										<h2>2. Derecho de desistimiento</h2>
										<p>De acuerdo con el <strong>Real Decreto Legislativo 1/2007</strong>, el
											consumidor dispone de un plazo de <strong>14 días naturales</strong> desde
											la recepción del pedido para ejercer su derecho de desistimiento sin
											necesidad de justificar su decisión.</p>
										<p>Para ejercer este derecho, deberá comunicar su decisión mediante un correo
											electrónico a:</p>
										<p><strong><a
													href="mailto:contacto@box-modulares.es">contacto@box-modulares.es</a></strong>
										</p>
										<p>indicando:</p>
										<ul>
											<li>
												<p>Nombre y apellidos.</p>
											</li>
											<li>
												<p>Número de pedido.</p>
											</li>
											<li>
												<p>Producto o productos que desea devolver.</p>
											</li>
											<li>
												<p>Fecha de recepción del pedido.</p>
											</li>
										</ul>
										<h2>3. Condiciones para aceptar una devolución</h2>
										<p>Para que una devolución sea aceptada, los productos deberán:</p>
										<ul>
											<li>
												<p>Estar en perfecto estado.</p>
											</li>
											<li>
												<p>No haber sido utilizados ni montados.</p>
											</li>
											<li>
												<p>Conservar su embalaje original.</p>
											</li>
											<li>
												<p>Incluir todos los accesorios, manuales y documentación suministrados.
												</p>
											</li>
											<li>
												<p>Estar correctamente protegidos durante el transporte de devolución.
												</p>
											</li>
										</ul>
										<p>Arquisset de Construccio S.L. se reserva el derecho de rechazar devoluciones
											que no cumplan estas condiciones cuando la pérdida de valor del producto sea
											consecuencia de una manipulación distinta de la necesaria para comprobar su
											naturaleza, características o funcionamiento.</p>
										<h2>4. Productos excluidos del derecho de desistimiento</h2>
										<p>De conformidad con la legislación vigente, no podrán devolverse, entre otros:
										</p>
										<ul>
											<li>
												<p>Productos fabricados conforme a las especificaciones del cliente.</p>
											</li>
											<li>
												<p>Productos claramente personalizados.</p>
											</li>
											<li>
												<p>Productos confeccionados bajo pedido o a medida.</p>
											</li>
											<li>
												<p>Productos precintados que no sean aptos para su devolución por
													razones de protección de la salud o higiene y cuyo precinto haya
													sido retirado.</p>
											</li>
											<li>
												<p>Otros productos excluidos por el artículo 103 del Real Decreto
													Legislativo 1/2007.</p>
											</li>
										</ul>
										<h2>5. Productos dañados o defectuosos</h2>
										<p>Si el cliente recibe un producto dañado durante el transporte, defectuoso o
											diferente al solicitado, deberá comunicar la incidencia en el menor plazo
											posible enviando un correo electrónico a <strong><a
													href="mailto:contacto@box-modulares.es">contacto@box-modulares.es</a></strong>.
										</p>
										<p>La comunicación deberá incluir:</p>
										<ul>
											<li>
												<p>Número de pedido.</p>
											</li>
											<li>
												<p>Descripción de la incidencia.</p>
											</li>
											<li>
												<p>Fotografías del producto y del embalaje.</p>
											</li>
										</ul>
										<p>Una vez comprobada la incidencia, Arquisset de Construccio S.L. ofrecerá la
											reparación, sustitución, devolución del importe o cualquier otra solución
											prevista por la legislación vigente.</p>
										<h2>6. Procedimiento de devolución</h2>
										<p>Una vez autorizada la devolución, el cliente recibirá las instrucciones
											necesarias para realizar el envío del producto.</p>
										<p>Se recomienda conservar el justificante del envío hasta la finalización del
											proceso.</p>
										<h2>7. Gastos de devolución</h2>
										<p>Cuando la devolución se deba al ejercicio del derecho de desistimiento,
											<strong>los gastos directos del envío de devolución serán asumidos por el
												cliente</strong>, salvo que la legislación aplicable disponga otra cosa
											o que Arquisset de Construccio S.L. indique expresamente lo contrario.</p>
										<p>En caso de error en el envío, producto defectuoso o falta de conformidad,
											<strong>Arquisset de Construccio S.L. asumirá los gastos de devolución y, en
												su caso, de un nuevo envío</strong>.</p>
										<h2>8. Reembolsos</h2>
										<p>Una vez recibidos los productos y comprobado su estado, el reembolso se
											efectuará utilizando el mismo medio de pago empleado por el cliente, salvo
											acuerdo expreso en contrario.</p>
										<p>El reembolso se realizará <strong>en un plazo máximo de 14 días
												naturales</strong> desde la recepción de la comunicación del
											desistimiento, pudiendo ser retenido hasta recibir los productos o hasta que
											el cliente aporte una prueba suficiente de su devolución, conforme a la
											legislación vigente.</p>
										<h2>9. Cambios de productos</h2>
										<p>Si el cliente desea cambiar un producto por otro diferente, deberá ponerse en
											contacto con nuestro servicio de atención al cliente.</p>
										<p>Los cambios estarán sujetos a la disponibilidad del nuevo producto
											solicitado.</p>
										<p>En caso de diferencia de precio, se realizará el correspondiente abono o
											cargo.</p>
										<h2>10. Garantía legal</h2>
										<p>Todos los productos vendidos a consumidores cuentan con la garantía legal
											prevista por la normativa española.</p>
										<p>En caso de falta de conformidad, el consumidor podrá solicitar la reparación,
											sustitución, reducción del precio o resolución del contrato, en los términos
											establecidos por la legislación aplicable.</p>
										<p>La garantía no cubrirá los daños derivados de:</p>
										<ul>
											<li>
												<p>Uso indebido.</p>
											</li>
											<li>
												<p>Manipulación incorrecta.</p>
											</li>
											<li>
												<p>Desgaste normal por el uso.</p>
											</li>
											<li>
												<p>Instalaciones o modificaciones realizadas por terceros no
													autorizados.</p>
											</li>
										</ul>
										<h2>11. Atención al cliente</h2>
										<p>Para cualquier consulta relacionada con devoluciones, cambios o reembolsos,
											puede contactar con:</p>
