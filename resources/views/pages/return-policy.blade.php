											española y, en particular, por el <strong>Real Decreto Legislativo
												1/2007</strong>, la <strong>Ley 34/2002 (LSSI-CE)</strong> y el
											<strong>Reglamento (UE) 2016/679 (RGPD)</strong>, sin perjuicio de los
											derechos que correspondan a los consumidores conforme a la normativa de la
											Unión Europea.</p>
